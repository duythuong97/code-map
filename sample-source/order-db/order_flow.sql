	END APPLY_TAX_API;

	PROCEDURE CANCEL_ORDER(p_order_id IN NUMBER)
	IS
		v_status VARCHAR2(20) := 'CANCELLED';
	BEGIN
		UPDATE ORDER_HEADER
			 SET STATUS = v_status
		 WHERE ORDER_ID = p_order_id;
		DELETE FROM INVENTORY_RESERVATION
		 WHERE ORDER_ID = p_order_id;
		INSERT INTO SHIPMENT_AUDIT (
			AUDIT_ID,
			SHIPMENT_ID,
			STATUS
		) SELECT SHIPMENT_AUDIT_SEQ.NEXTVAL,
						 SHIPMENT_ID,
						 'CANCELLED'
				FROM SHIPMENT
			 WHERE ORDER_ID = p_order_id;
		-- CANCEL_ORDER releases reservations
		IF SQL%ROWCOUNT = 0 THEN
			NULL;
		END IF;

		-- Column write fixture follows exact snippet from package evidence.
		UPDATE ORDER_HEADER SET STATUS = :status WHERE ORDER_ID = :order_id;
	END CANCEL_ORDER; -- UPDATE ORDER_HEADER SET STATUS = :status

	PROCEDURE ALLOCATE_ORDER(p_order_id IN NUMBER)
	IS
		v_stock NUMBER;
		v_sql VARCHAR2(4000);
	BEGIN
		SELECT COUNT(*)
			INTO v_stock
			FROM ORDER_HEADER
		 WHERE ORDER_ID = p_order_id;
		IF v_stock > 0 THEN
			INSERT INTO FULFILLMENT_ALLOCATION
				(ALLOCATION_ID, ORDER_ID, STATUS)
			VALUES (FULFILLMENT_SEQ.NEXTVAL, p_order_id, 'ALLOCATED');
			UPDATE ORDER_HEADER
				 SET STATUS = 'ALLOCATED'
			 WHERE ORDER_ID = p_order_id;
		ELSE
			-- Insufficient stock creates BACKORDER
			INSERT INTO BACKORDER (
				BACKORDER_ID,
				ORDER_ID,
				QUANTITY
			) VALUES (
				BACKORDER_SEQ.NEXTVAL, p_order_id, 1
			);
		END IF;
		v_sql := 'UPDATE ORDER_HEADER SET STATUS = ''ALLOCATED'' WHERE ORDER_ID = :id';
		EXECUTE IMMEDIATE v_sql;
		-- Runtime SQL target cannot be resolved
		INSERT INTO SHIPMENT
			(SHIPMENT_ID, ORDER_ID, STATUS)
		VALUES (SHIPMENT_SEQ.NEXTVAL, p_order_id, 'CREATED');
		INSERT INTO SHIPMENT_PACKAGE
			(PACKAGE_ID, SHIPMENT_ID)
		SELECT PACKAGE_SEQ.NEXTVAL, SHIPMENT_ID
			FROM SHIPMENT
		 WHERE ORDER_ID = p_order_id;
		-- ALLOCATE_ORDER creates allocation or backorder
		NULL;
	END ALLOCATE_ORDER;

END PKG_ORDER;
