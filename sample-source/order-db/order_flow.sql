CREATE OR REPLACE TRIGGER TRG_SHIPMENT_AUDIT
AFTER UPDATE OF STATUS ON SHIPMENT
FOR EACH ROW
WHEN (OLD.STATUS <> NEW.STATUS)
BEGIN
	INSERT INTO SHIPMENT_AUDIT (
		AUDIT_ID,
		SHIPMENT_ID,
		STATUS
	) VALUES (
		SHIPMENT_AUDIT_SEQ.NEXTVAL,
		:NEW.SHIPMENT_ID,
		:NEW.STATUS
	);
	-- Shipment status change inserts audit row
END;
