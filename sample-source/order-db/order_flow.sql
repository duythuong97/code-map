CREATE OR REPLACE PACKAGE BODY PKG_ORDER AS

	PROCEDURE CREATE_ORDER(
		p_customer_id IN NUMBER,
		p_request_key IN VARCHAR2
	) IS
		v_order_id NUMBER;
		v_total NUMBER;
	BEGIN
		v_order_id := ORDER_SEQ.NEXTVAL;
		VALIDATE_LINES(p_customer_id);
		v_total := CALCULATE_TOTAL(p_customer_id);
		INSERT INTO ORDER_HEADER (
			ORDER_ID, CUSTOMER_ID, STATUS, TOTAL_AMOUNT, CREATED_AT
		) VALUES (
			v_order_id, p_customer_id, 'PENDING', v_total, SYSTIMESTAMP
		);
		INSERT INTO ORDER_LINE (
			ORDER_LINE_ID, ORDER_ID, PRODUCT_ID, QUANTITY, UNIT_PRICE
		) SELECT ORDER_LINE_SEQ.NEXTVAL, v_order_id, PRODUCT_ID, QUANTITY, UNIT_PRICE
				FROM ORDER_STAGING_LINES
			 WHERE CUSTOMER_ID = p_customer_id;
		INSERT INTO INVENTORY_RESERVATION (
			RESERVATION_ID, ORDER_ID, PRODUCT_ID, QUANTITY, STATUS
		) SELECT RESERVATION_SEQ.NEXTVAL, v_order_id, PRODUCT_ID, QUANTITY, 'RESERVED'
				FROM ORDER_LINE
			 WHERE ORDER_ID = v_order_id;
		INSERT INTO PAYMENT_TRANSACTION (
			PAYMENT_ID, ORDER_ID, STATUS, AMOUNT
		) VALUES (
			PAYMENT_SEQ.NEXTVAL, v_order_id, 'PENDING', v_total
		);
	EXCEPTION
		WHEN DUP_VAL_ON_INDEX THEN
			INSERT INTO PAYMENT_TRANSACTION (
				PAYMENT_ID, ORDER_ID, STATUS, AMOUNT
			) VALUES (
				PAYMENT_SEQ.NEXTVAL, v_order_id, 'FAILED', 0
			);
			RAISE;
	END CREATE_ORDER;

	PROCEDURE VALIDATE_LINES(p_customer_id IN NUMBER) IS
	BEGIN
		NULL;
	END VALIDATE_LINES;

	FUNCTION CALCULATE_TOTAL(p_customer_id IN NUMBER)
		RETURN NUMBER
	IS
		v_rate NUMBER;
		v_total NUMBER;
	BEGIN
		SELECT SUM(QUANTITY * UNIT_PRICE)
			INTO v_total
			FROM ORDER_STAGING_LINES
		 WHERE CUSTOMER_ID = p_customer_id;
		SELECT rate FROM TAX_SCHEMA.TAX_RATE@TAX_DB_LINK INTO v_rate;
		RETURN v_total * v_rate;
	END CALCULATE_TOTAL;

	PROCEDURE APPLY_TAX_API(p_order_id IN NUMBER) IS
